import type { ColorScheme, Intent, Tokens } from './tokens.ts';

const INTENTS = ['primary', 'brand', 'success', 'warning', 'danger', 'info', 'neutral'] as const;

const rem = (px: number) => `${px / 16}rem`;
const kebab = (key: string) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function intentVars(name: string, intent: Intent): [string, string][] {
  return [
    [`--color-${name}`, intent.solid],
    [`--color-${name}-hover`, intent.solidHover],
    [`--color-on-${name}`, intent.onSolid],
    [`--color-${name}-soft`, intent.soft],
    [`--color-on-${name}-soft`, intent.onSoft],
  ];
}

/** Semantic colour variables for one scheme, e.g. `--color-surface`, `--color-on-primary`. */
export function schemeVars(scheme: ColorScheme): [string, string][] {
  return [
    ['--color-bg', scheme.bg],
    ['--color-surface', scheme.surface],
    ['--color-surface-muted', scheme.surfaceMuted],
    ['--color-surface-raised', scheme.surfaceRaised],
    ['--color-fg', scheme.fg],
    ['--color-fg-muted', scheme.fgMuted],
    ['--color-border', scheme.border],
    ['--color-input', scheme.borderInput],
    ['--color-focus', scheme.focus],
    ['--color-overlay', scheme.overlay],
    ...INTENTS.flatMap((name) => intentVars(name, scheme[name])),
    ...scheme.chart.map((value, i): [string, string] => [`--color-chart-${i + 1}`, value]),
  ];
}

const block = (selector: string, vars: [string, string][], extra: string[] = []) =>
  [
    `${selector} {`,
    ...extra.map((l) => `  ${l}`),
    ...vars.map(([k, v]) => `  ${k}: ${v};`),
    '}',
  ].join('\n');

/**
 * Tailwind v4 theme. Replaces Tailwind's default colours, fonts, text sizes, radii and shadows so
 * only GGEM tokens are available. Light is the default; `data-theme="dark"` (or `.dark`) on any
 * element switches that subtree, and `data-theme="light"` switches back.
 */
export function toThemeCss(t: Tokens): string {
  const theme: [string, string][] = [
    ['--color-*', 'initial'],
    ['--font-*', 'initial'],
    ['--text-*', 'initial'],
    ['--radius-*', 'initial'],
    ['--shadow-*', 'initial'],
    ['--color-white', '#ffffff'],
    ['--color-black', '#000000'],
    ...Object.entries(t.palette).flatMap(([name, scale]) =>
      Object.entries(scale).map(([step, value]): [string, string] => [
        `--color-${name}-${step}`,
        value,
      ])
    ),
    ...schemeVars(t.colors.light),
    ...Object.entries(t.fontFamily).map(([name, stack]): [string, string] => [
      `--font-${name}`,
      stack.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', '),
    ]),
    ...Object.entries(t.fontWeight).map(([name, w]): [string, string] => [
      `--font-weight-${name}`,
      String(w),
    ]),
    ...Object.entries(t.fontSize).flatMap(([name, [fs, lh]]): [string, string][] => [
      [`--text-${name}`, rem(fs)],
      [`--text-${name}--line-height`, rem(lh)],
    ]),
    ['--spacing', rem(t.spacingUnit)],
    ...Object.entries(t.radius).map(([name, r]): [string, string] => [
      `--radius-${name}`,
      r === 9999 ? 'calc(infinity * 1px)' : rem(r),
    ]),
    ...Object.entries(t.shadow).map(([name, s]): [string, string] => [`--shadow-${name}`, s]),
    ...Object.entries(t.duration).map(([name, ms]): [string, string] => [
      `--duration-${name}`,
      `${ms}ms`,
    ]),
    ...Object.entries(t.easing).map(([name, e]): [string, string] => [`--ease-${name}`, e]),
    ...Object.entries(t.size).map(([name, px]): [string, string] => [
      `--size-${kebab(name)}`,
      rem(px),
    ]),
    ...Object.entries(t.zIndex).map(([name, z]): [string, string] => [`--z-${name}`, String(z)]),
  ];

  const indent = (css: string) =>
    css
      .split('\n')
      .map((l) => `  ${l}`)
      .join('\n');

  // Light first, dark second: an element only matches its own scheme's selector, so nested
  // light/dark subtrees work. `:root.dark` and `:root[data-theme]` outrank Tailwind's `:root`.
  return [
    '/* Generated by @ggem/tokens from src/tokens.ts. Do not edit. */',
    '',
    '@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *, .dark, .dark *));',
    '',
    block('@theme static', theme),
    '',
    '@layer theme {',
    indent(
      block(':root, [data-theme="light"]', schemeVars(t.colors.light), ['color-scheme: light;'])
    ),
    indent(
      block(
        ':root[data-theme="dark"], :root.dark, [data-theme="dark"], .dark',
        schemeVars(t.colors.dark),
        ['color-scheme: dark;']
      )
    ),
    '}',
    '',
  ].join('\n');
}
